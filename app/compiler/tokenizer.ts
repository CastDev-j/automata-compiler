class Tokenizer {
  private readonly spaceColumnIndex = charToIndex[" "];

  private readonly compoundOperators = [
    "===",
    "!==",
    "==",
    "!=",
    "<=",
    ">=",
    "&&",
    "||",
    "++",
    "--",
  ];

  private readonly singleOperators = [
    "+",
    "-",
    "*",
    "/",
    "%",
    "<",
    ">",
    "=",
    "!",
    "&",
    "|",
    ".",
    ",",
    ";",
    ":",
    "{",
    "}",
    "(",
    ")",
    "[",
    "]",
  ];

  private normalizeTokenByLexeme(
    fallbackToken: TokenInfo,
    lexeme: string,
  ): TokenInfo {
    if (fallbackToken.word === "STRING") {
      return STRING_TOKEN;
    }

    const reservedToken = reservedWordToToken[lexeme];
    if (reservedToken) {
      return reservedToken;
    }

    const literalToken = literalTokenToToken[lexeme];
    if (literalToken) {
      return literalToken;
    }

    if (/^\d+$/.test(lexeme)) {
      return INT_TOKEN;
    }

    if (/^\d+\.\d+$/.test(lexeme)) {
      return FLOAT_TOKEN;
    }

    if (/^[a-zñ_][a-zñ0-9_]*$/i.test(lexeme)) {
      return ID_TOKEN;
    }

    return fallbackToken;
  }

  private shouldConsumeChar(tokenInfo: TokenInfo, char: string): boolean {
    if (
      tokenInfo.word === "ID" ||
      tokenInfo.word === "INT" ||
      tokenInfo.word === "FLOAT"
    ) {
      return false;
    }

    if (tokenInfo.word === "STRING") {
      return char === '"';
    }

    if (tokenInfo.word.length === 1) {
      return char === tokenInfo.word;
    }

    return false;
  }

  public lexer(input: string): LexedToken[] {
    const tokens: LexedToken[] = [];
    let i = 0;
    const n = input.length;

    while (i < n) {
      const currentChar = input[i] ?? "";

      //! Saltar espacios y saltos de línea
      if (/\s/.test(currentChar)) {
        i++;
        continue;
      }

      const remainingInput = input.slice(i);

      if (currentChar === '"') {
        const start = i;
        i++;

        while (i < n && input[i] !== '"') {
          i++;
        }

        if (i >= n) {
          throw new Error(`String sin cerrar en posición ${start}`);
        }

        i++;
        tokens.push({
          token: 7000,
          word: "STRING",
          value: input.slice(start, i),
        });
        continue;
      }

      const identifierMatch = remainingInput.match(/^[a-zñ_][a-zñ0-9_]*/i);
      if (identifierMatch) {
        const lexeme = identifierMatch[0];
        const tokenInfo = this.normalizeTokenByLexeme(ID_TOKEN, lexeme);
        tokens.push({
          token: tokenInfo.token,
          word: tokenInfo.word,
          value: lexeme,
        });
        i += lexeme.length;
        continue;
      }

      const numberMatch = remainingInput.match(/^\d+(?:\.\d+)?/);
      if (numberMatch) {
        const lexeme = numberMatch[0];
        const tokenInfo = lexeme.includes(".") ? FLOAT_TOKEN : INT_TOKEN;
        tokens.push({
          token: tokenInfo.token,
          word: tokenInfo.word,
          value: lexeme,
        });
        i += lexeme.length;
        continue;
      }

      const compoundOperator = this.compoundOperators.find((operator) =>
        remainingInput.startsWith(operator),
      );
      if (compoundOperator) {
        const tokenInfo = literalTokenToToken[compoundOperator];
        if (!tokenInfo) {
          throw new Error(`Operador no reconocido: "${compoundOperator}"`);
        }
        tokens.push({
          token: tokenInfo.token,
          word: tokenInfo.word,
          value: compoundOperator,
        });
        i += compoundOperator.length;
        continue;
      }

      const singleOperator = this.singleOperators.find((operator) =>
        remainingInput.startsWith(operator),
      );
      if (singleOperator) {
        const tokenInfo = literalTokenToToken[singleOperator];
        if (!tokenInfo) {
          throw new Error(`Operador no reconocido: "${singleOperator}"`);
        }
        tokens.push({
          token: tokenInfo.token,
          word: tokenInfo.word,
          value: singleOperator,
        });
        i += singleOperator.length;
        continue;
      }

      let currentRow = 0;
      let lexeme = "";
      let lastValidToken: TokenInfo | null = null;
      let lastValidLexeme = "";
      let lastValidIndex = i;

      while (i < n) {
        const char = input.charAt(i);
        const colIndex =
          charToIndex[char] ??
          (this.spaceColumnIndex !== undefined && /\s/.test(char)
            ? this.spaceColumnIndex
            : undefined);

        //! Error caracteres no definidos
        if (colIndex === undefined) {
          if (lexeme.length === 0) {
            throw new Error(
              `Carácter no reconocido: "${char}" en posición ${i}`,
            );
          }
          break;
        }

        const currentTransitions =
          currentRow === IDENTIFIER_STATE
            ? transitionTable[identifierTransitionRowIndex]
            : transitionTable[currentRow];
        if (!currentTransitions) {
          const terminalToken = tokenTable[currentRow];
          if (terminalToken) {
            lastValidToken = terminalToken;
            lastValidLexeme = lexeme;
            lastValidIndex = i;
            break;
          }
          throw new Error(`Estado de transición inválido: ${currentRow}`);
        }

        const nextRow = currentTransitions[colIndex] ?? 0;

        //? Capturar y grabar token válido
        if (nextRow < 0) {
          const tokenCode = Math.trunc(Math.abs(nextRow));
          const tokenInfo = tokenByCode[tokenCode] ?? tokenTable[currentRow];
          if (tokenInfo) {
            const consumeChar = this.shouldConsumeChar(tokenInfo, char);
            lastValidToken = tokenInfo;
            lastValidLexeme = consumeChar ? lexeme + char : lexeme;
            lastValidIndex = consumeChar ? i + 1 : i;
          }
        }

        //? Si no hay transición y no es token válido
        if (nextRow === 0 || nextRow === undefined) {
          break;
        }

        currentRow = nextRow;
        lexeme += char;
        i++;

        //? Si llegamos a un estado final (valor negativo)
        if (nextRow < 0) {
          break;
        }
      }

      //? Si encontramos un token válido
      if (lastValidToken) {
        const normalizedToken = this.normalizeTokenByLexeme(
          lastValidToken,
          lastValidLexeme,
        );

        tokens.push({
          token: normalizedToken.token,
          word: normalizedToken.word,
          value: lastValidLexeme,
        });
        i = lastValidIndex;
      } else if (lexeme.length > 0) {
        //? Si no es token válido pero tenemos algo, podría ser ID
        const firstChar = lexeme.charAt(0);
        const colIndex = charToIndex[firstChar];
        if (colIndex !== undefined) {
          const startRow = transitionTable[0];
          if (!startRow) {
            throw new Error(
              "Tabla de transición inválida: falta la fila inicial",
            );
          }

          const idRow = startRow[colIndex];
          if (idRow === IDENTIFIER_STATE) {
            const normalizedToken = this.normalizeTokenByLexeme(
              ID_TOKEN,
              lexeme,
            );
            tokens.push({
              token: normalizedToken.token,
              word: normalizedToken.word,
              value: lexeme,
            });
          } else {
            throw new Error(
              `Token no reconocido: "${lexeme}" en posición ${i - lexeme.length}`,
            );
          }
        }
      }

      //? Si no avanzamos, hay un error
      if (lexeme === "" && i < n) {
        throw new Error(
          `Carácter no reconocido: "${input[i]}" en posición ${i}`,
        );
      }
    }

    return tokens;
  }
}

const tokenizer = new Tokenizer();

function lexer(input: string): LexedToken[] {
  return tokenizer.lexer(input);
}

export { Tokenizer, lexer };
